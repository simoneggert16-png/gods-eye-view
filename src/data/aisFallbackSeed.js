/**
 * Return the fallback vessels snapshot with current ISO timestamps and optional
 * maxRows limit.
 * @param {number} [maxRows=500]
 * @returns {Array<Object>}
 */
export function getAisFallbackRows(maxRows = 500) {
  const limit = Math.max(1, Math.min(Number(maxRows) || 500, AIS_FALLBACK_VESSELS.length));
  const now = new Date().toISOString();
  return AIS_FALLBACK_VESSELS.slice(0, limit).map((vessel) => ({
    ...vessel,
    last_position_utc: now,
  }));
}
